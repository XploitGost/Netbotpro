import assert from 'node:assert/strict';
import {recordPacket,resetTraffic,trafficPoints,trafficRates,hoverSample,packetTime} from './trafficModel.js';
const now=1800000004000;
resetTraffic();
const packet={id:1,ts:now-1500,length:1000,direction:'INCOMING',risk_level:'medium'};
recordPacket(packet,now);recordPacket(packet,now);
recordPacket({id:2,ts:now-1000,length:500,direction:'OUTGOING'},now);
const rates=trafficRates(now),points=trafficPoints(now);
assert.equal(rates.inbound_bps,4000);assert.equal(rates.outbound_bps,2000);assert.equal(rates.packets_per_second,1);
assert.equal(points.length,1);assert.equal(points[0].inbound*1e6,rates.inbound_bps);
assert.equal(points[0].suspicious,.004);
const saved=JSON.stringify(points);
recordPacket({id:3,ts:now+500,length:99999,direction:'INCOMING'},now+500);
assert.equal(JSON.stringify(trafficPoints(now+500)),saved,'Current incomplete bucket does not overwrite historical bars');
assert.equal(hoverSample(points,points[0].time-10000),null);
assert.equal(hoverSample(points,points[0].time+900),points[0]);
assert.deepEqual(trafficRates(now+10000),{inbound_bps:0,outbound_bps:0,packets_per_second:0});
assert.equal(packetTime({ts:now/1000},now),now);
resetTraffic();assert.equal(trafficPoints(now).length,0);
console.log('PASS: time normalization, packet deduplication, shared rate/bar values, risk rates, immutable completed buckets, empty-area hover, idle decay and session reset.');
