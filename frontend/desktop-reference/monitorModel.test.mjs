import assert from 'node:assert/strict';
import {packetTime,packetRisk,packetProtocol,packetInfo,flowRows,orderedEvidence,evidenceDate,capturedDissection,destinationDomain} from './monitorModel.js';
assert.equal(packetTime('20:20:26'),'20:20:26');
assert.equal(packetTime('20:20:26.712'),'20:20:26.712');
assert.equal(packetTime('25:20:26'),'-');
assert.equal(packetTime(null),'-');
assert.equal(packetTime('1791390473'),packetTime(1791390473));
assert.match(packetTime('2026-10-07T14:32:09.712Z'),/\d{2}:\d{2}:\d{2}\.712$/);
assert.equal(packetTime('bad'),'-');
assert.equal(packetRisk({risk_level:'low',summary:'not a critical incident'}),'low');
assert.equal(packetRisk({risk_level:'medium',is_alert:true}),'medium');
assert.equal(packetRisk({is_alert:true}),'high');
assert.equal(packetRisk(null),'low');
assert.equal(packetProtocol({proto:'TCP',app_protocol:'UNKNOWN'}),'TCP');
assert.equal(packetProtocol({proto:'TCP',app_protocol:'HTTPS'}),'HTTPS');
assert.equal(packetInfo({payload_preview:'must not become table info'}),'-');
assert.deepEqual(destinationDomain({destination_domain:'example.net',destination_domain_source:'TLS SNI'}),{domain:'example.net',source:'TLS SNI',candidates:[]});
assert.deepEqual(destinationDomain({dns_qname:'example.net'}),{domain:'-',source:'',candidates:[]});
assert.deepEqual(destinationDomain({destination_domain_source:'DNS answer (ambiguous)',destination_domain_candidates:['one.example','two.example']}),{domain:'Multiple possible domains',source:'DNS answer (ambiguous)',candidates:['one.example','two.example']});
assert.deepEqual(destinationDomain({destination_domain_candidates:'invalid'}),{domain:'-',source:'',candidates:[]});
assert.deepEqual(flowRows({seq:0,ack:0,ttl:52}),[['Sequence Number',0],['Acknowledgment Number',0],['TTL / Hop Limit',52]]);
assert.deepEqual(flowRows({}),[]);
const unordered=[{id:1,ts:'2026-10-07T18:00:00Z'},{id:2,timestamp:'2026-10-07T18:00:02Z'},{id:3,ts:'invalid'}];
assert.deepEqual(orderedEvidence(unordered).map(entry=>entry.index),[1,0,2]);
assert.equal(unordered[0].id,1);
assert.match(evidenceDate(unordered[0].ts),/^07\/10\/2026 /);
assert.equal(evidenceDate(null),'-');
const fallback=capturedDissection({proto:'TCP',src:'192.0.2.1',seq:0,ack:0,window:0});
assert.equal(fallback.metadata_fallback,true);
assert.equal(fallback.layers.some(layer=>layer.name==='Ethernet'),false);
assert.equal(fallback.layers.find(layer=>layer.name==='TCP').fields.find(field=>field.label==='Window Size').value,0);
assert.deepEqual(fallback.hex.rows,[]);
console.log('PASS: millisecond timestamps, explicit risk, transport fallback, metadata-only info, zero-valued fields and missing metadata.');
