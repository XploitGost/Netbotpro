import assert from 'node:assert/strict';
import {protocolDistribution,formatTrafficRate,metricChange,endpointActivity,captureInterfaceLabel,resolveCaptureInterface,activeConnectionDisplay,mergeHealthMetrics} from './dashboardModel.js';
assert.equal(mergeHealthMetrics({alert_engine:{health:'healthy'}},{alert_engine:{}}).alert_engine.health,'healthy');
assert.equal(mergeHealthMetrics({alert_engine:{health:'healthy'}},{alert_engine:{health:'degraded'}}).alert_engine.health,'degraded');
const tap={value:'tap',name:'Local Area Connection',description:'TAP-Windows Adapter V9',is_up:true,connection_name:'Ivacy'};
assert.deepEqual(activeConnectionDisplay([tap],'tap','tap'),{name:'Ivacy',detail:'Active: Local Area Connection - VPN (TAP)'});
const wifi={value:'wifi',name:'Wi-Fi',description:'Wireless LAN',is_up:true};
assert.deepEqual(activeConnectionDisplay([{...tap,is_up:false},wifi],'wifi','tap'),{name:'Wi-Fi',detail:'Active: Wi-Fi - Wireless LAN'});
assert.equal(activeConnectionDisplay([{name:'amir',value:'ras:amir',is_up:true}],'ras:amir','tap').name,'amir');
assert.equal(activeConnectionDisplay([{...tap,is_up:false}],'tap','tap').name,'Connection unavailable');
