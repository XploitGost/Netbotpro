assert.equal(resolveCaptureInterface([adapter],'missing'),null);
assert.deepEqual(captureInterfaceLabel({name:'Local Area Connection',description:'TAP-Windows Adapter V9'}),{name:'Local Area Connection - VPN (TAP)',vpn:true});
assert.deepEqual(captureInterfaceLabel({name:'amir',value:'ras:amir',description:'PPP VPN via WAN Miniport (IP)'}),{name:'amir - VPN (PPP)',vpn:true});
assert.equal(captureInterfaceLabel({name:'Wi-Fi',description:'MediaTek Wi-Fi 6'}).vpn,false);
